fn decode_high_byte(page: u8, byte: u8) -> Option<char> {
    let idx = (byte - 0x80) as usize;
    let table = high_table(page)?;
    match table[idx] {
        '\0' => None,
        ch => Some(ch),
    }
}

fn high_table(page: u8) -> Option<&'static [char; 128]> {
    match page {
        0 => Some(&PC437),
        1 => Some(&KATAKANA),
        2 => Some(&PC850),
        3 => Some(&PC860),
        4 => Some(&PC863),
        5 => Some(&PC865),
        16 => Some(&WPC1252),
        17 => Some(&PC866),
        18 => Some(&PC852),
        19 => Some(&PC858),
        255 => Some(&PAGE255),
        _ => None,
    }
}

