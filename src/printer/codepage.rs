pub fn decode_byte(code_page: u8, character_set: u8, byte: u8) -> Option<char> {
    match byte {
        0x00 | 0x7F => None,
        0x01..=0x1F => None,
        0x20..=0x7E => Some(apply_character_set(character_set, byte)),
        0x80..=0xFF => Some(decode_high_byte(code_page, byte).unwrap_or(' ')),
    }
}

pub fn decode_bytes(code_page: u8, character_set: u8, bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len());
    for &byte in bytes {
        if let Some(ch) = decode_byte(code_page, character_set, byte) {
            out.push(ch);
        }
    }
    out
}

fn apply_character_set(character_set: u8, byte: u8) -> char {
    let Some(slot) = charset_slot(byte) else {
        return byte as char;
    };
    charset_row(character_set)[slot]
}

fn charset_slot(byte: u8) -> Option<usize> {
    Some(match byte {
        0x23 => 0,
        0x24 => 1,
        0x40 => 2,
        0x5B => 3,
        0x5C => 4,
        0x5D => 5,
        0x5E => 6,
        0x60 => 7,
        0x7B => 8,
        0x7C => 9,
        0x7D => 10,
        0x7E => 11,
        _ => return None,
    })
}

